def calculate_quintessence(cards: List[Dict]) -> Dict:
    """
    Calculate the Quintessence (Квинтэссенция расклада) using classical esoteric numerology:
    - Major Arcana contribute their number (0..21)
    - Numbered Minor Arcana contribute 1..10 (Court cards = 0 or reduced rank)
    - Reduce sum via theosophical reduction to 1..21 (if > 21, sum digits).
    """
    total = 0
    for c in cards:
        if c["arcana_type"] == "Старший Аркан":
            total += int(c["number"])
        elif int(c["number"]) <= 10:
            total += int(c["number"])
        else:
            # Court cards: Page=11->2, Knight=12->3, Queen=13->4, King=14->5
            total += sum(int(d) for d in str(c["number"]))

    while total > 21:
        total = sum(int(d) for d in str(total))

    quint_major = next((m for m in FULL_DECK if m["arcana_type"] == "Старший Аркан" and m["number"] == total), FULL_DECK[0])
    # If total is between 10 and 21, also compute inner single-digit reduction (e.g., 14 Умеренность -> 1+4 = 5 Иерофант)
    inner_num = sum(int(d) for d in str(total)) if total >= 10 else None
    inner_major = (
        next((m for m in FULL_DECK if m["arcana_type"] == "Старший Аркан" and m["number"] == inner_num), None)
        if inner_num is not None and inner_num != total
        else None
    )
    return {
        "number": total,
        "card": quint_major,
        "inner_card": inner_major,
    }


def evaluate_elemental_dignities(cards: List[Dict]) -> Dict:
    """
    Analyze Elemental Balance & Golden Dawn Elemental Dignities across drawn cards:
    - Fire & Water = opposing/neutralizing (conflict between passion and emotion)
    - Air & Earth = opposing/neutralizing (abstract mind vs material pragmatism)
    - Fire & Air = active/friendly (mutually reinforcing energy & ideas)
    - Water & Earth = receptive/friendly (fertile emotional & material support)
    """
    counts = {"Огонь": 0, "Вода": 0, "Воздух": 0, "Земля": 0}
    majors_count = 0
    reversed_count = 0

    for c in cards:
        el = c.get("element", "Воздух")
        if el in counts:
            counts[el] += 1
        if c["arcana_type"] == "Старший Аркан":
            majors_count += 1
        if c.get("is_reversed"):
            reversed_count += 1

    dominant = max(counts.items(), key=lambda x: x[1])[0]
    missing = [k for k, v in counts.items() if v == 0]

    return {
        "counts": counts,
        "dominant_element": dominant,
        "missing_elements": missing,
        "majors_count": majors_count,
        "reversed_count": reversed_count,
    }


def draw_tarot_spread(
    spread_type: str = "triplet",
    question: str = "",
    subject_name: str = "Кверент",
    allow_reversed: bool = True,
    custom_cards_query: Optional[List[str]] = None,
) -> Dict:
    """
    Draw a Tarot spread using cryptographic randomness mixed with question entropy,
    OR build the spread from cards specified by the user's own physical deck.
    Also draws the Bottom of the Deck ("Дно колоды") and computes Quintessence.
    """
    template = SPREAD_TEMPLATES.get(spread_type, SPREAD_TEMPLATES["triplet"])
    positions = template["positions"]

    rng = random.SystemRandom()
    deck_copy = [dict(c) for c in FULL_DECK]
    rng.shuffle(deck_copy)

    drawn_cards: List[Dict] = []

    if custom_cards_query:
        # Match user-provided card names
        used_ids = set()
        for idx, raw_card_str in enumerate(custom_cards_query):
            matched_card, is_rev = match_card_from_text(raw_card_str, used_ids)
            used_ids.add(matched_card["id"])
            pos_label = positions[idx][0] if idx < len(positions) else f"{idx + 1}. Позиция {idx + 1}"
            pos_x = positions[idx][1] if idx < len(positions) else min(0.9, 0.15 + idx * 0.22)
            pos_y = positions[idx][2] if idx < len(positions) else 0.52
            card_entry = dict(matched_card)
            card_entry["position_index"] = idx + 1
            card_entry["position_title"] = pos_label
            card_entry["x"] = pos_x
            card_entry["y"] = pos_y
            card_entry["is_reversed"] = is_rev
            card_entry["orientation_ru"] = "Перевёрнутая (⟲)" if is_rev else "Прямая (↑)"
            drawn_cards.append(card_entry)

        remaining = [c for c in deck_copy if c["id"] not in used_ids]
        bottom_card = dict(remaining[-1]) if remaining else dict(deck_copy[-1])
        bottom_card["is_reversed"] = False
        bottom_card["orientation_ru"] = "Прямая (↑)"
    else:
        for idx, (pos_label, px, py, _) in enumerate(positions):
            card_entry = dict(deck_copy[idx])
            is_rev = (rng.random() < 0.32) if allow_reversed else False
            card_entry["position_index"] = idx + 1
            card_entry["position_title"] = pos_label
            card_entry["x"] = px
            card_entry["y"] = py
            card_entry["is_reversed"] = is_rev
            card_entry["orientation_ru"] = "Перевёрнутая (⟲)" if is_rev else "Прямая (↑)"
            drawn_cards.append(card_entry)

        bottom_card = dict(deck_copy[-1])
        bottom_rev = (rng.random() < 0.28) if allow_reversed else False
        bottom_card["is_reversed"] = bottom_rev
        bottom_card["orientation_ru"] = "Перевёрнутая (⟲)" if bottom_rev else "Прямая (↑)"

    quint = calculate_quintessence(drawn_cards)
    elem_stats = evaluate_elemental_dignities(drawn_cards)

    return {
        "spread_type": spread_type,
        "spread_title": template["title"] if not custom_cards_query else f"Авторский расклад ({len(drawn_cards)} карт)",
        "subject_name": subject_name,
        "question": question,
        "cards": drawn_cards,
        "bottom_of_deck": bottom_card,
        "quintessence": quint,
        "elemental_stats": elem_stats,
    }


def match_card_from_text(query: str, exclude_ids: set) -> Tuple[Dict, bool]:
    """Fuzzy match a Russian/English card name and detect if reversed ('перев', 'п.п.', 'rev')."""
    q_low = query.lower().strip()
    is_rev = bool(re.search(r"(перев|п\.?\s*п\.?|rev|вверх\s+ногами|обратн)", q_low))

    # Normalize synonyms
    q_norm = (
        q_low.replace("чаш", "кубков")
        .replace("посохов", "жезлов")
        .replace("скипетров", "жезлов")
        .replace("дисков", "пентаклей")
        .replace("денариев", "пентаклей")
        .replace("монет", "пентаклей")
        .replace("дурак", "шут")
        .replace("жрец", "иерофант")
        .replace("правосудие", "справедливость")
        .replace("вселенная", "мир")
        .replace("эон", "суд")
        .replace("вожделение", "сила")
    )

    best_card = None
    best_score = -1

    for c in FULL_DECK:
        if c["id"] in exclude_ids:
            continue
        score = 0
        c_name = c["name_ru"].lower()
        for word in re.findall(r"[а-яёa-z0-9]+", c_name):
            if len(word) >= 3 and word[:4] in q_norm:
                score += 3
        if str(c["number"]) in re.findall(r"\b\d+\b", q_norm):
            score += 2
        if score > best_score:
            best_score = score
            best_card = c

    return (best_card or FULL_DECK[0]), is_rev


def format_spread_for_llm(spread: Dict) -> str:
    """Format full multi-tradition Tarot spread data into structured text for LLM synthesis."""
    lines = [
        f"=== РАСКЛАД ТАРО: {spread['spread_title']} ({spread['subject_name']}) ===",
        f"Вопрос / Запрос: {spread['question']}",
        "",
        "--- 1. ВЫПАВШИЕ АРКАНЫ ПО ПОЗИЦИЯМ ---",
    ]
    for c in spread["cards"]:
        meaning = c["rws_reversed"] if c["is_reversed"] else c["rws_upright"]
        lines.extend([
            f"Позиция {c['position_title']}:",
            f"• Карта: {c['name_ru']} [{c['roman']}] — {c['orientation_ru']} ({c['arcana_type']}, Стихия: {c['element_glyph']} {c['element']})",
            f"• Соответствия (Золотая Заря / Кроули / Каббала): {c['thoth_title']} | Астрология: {c['astro']} | Каббала: {c['kabbalah']}",
            f"• Значение (Школа Уэйта RWS): {meaning}",
            f"• Различия и нюансы других школ (Тот Кроули / Марсельское Таро / Папюс): {c['school_comparison']}",
            "",
        ])

    bot = spread["bottom_of_deck"]
    bot_meaning = bot["rws_reversed"] if bot["is_reversed"] else bot["rws_upright"]
    lines.extend([
        "--- 2. ДНО КОЛОДЫ (СКРЫТЫЙ МОТИВ, ПОДСОЗНАТЕЛЬНЫЙ ФОН СИТУАЦИИ) ---",
        f"• {bot['name_ru']} [{bot['roman']}] — {bot['orientation_ru']} (Стихия: {bot['element']}, Астро: {bot['astro']})",
        f"• Базовая трактовка: {bot_meaning}",
        f"• Сравнение школ: {bot['school_comparison']}",
        "",
    ])

    q = spread["quintessence"]
    q_card = q["card"]
    inner_str = (
        f" (внутренний корень через сложение: {q['inner_card']['roman']} {q['inner_card']['name_ru']})"
        if q.get("inner_card")
        else ""
    )
    lines.extend([
        "--- 3. КВИНТЭССЕНЦИЯ РАСКЛАДА (ИТОГОВЫЙ СОВЕТ ВЫСШИХ АРКАНОВ ПО СУММЕ) ---",
        f"• Старший Аркан {q_card['roman']} — {q_card['name_ru']}{inner_str}",
        f"• Совет по Уэйту: {q_card['rws_upright']}",
        f"• Сравнение школ: {q_card['school_comparison']}",
        "",
    ])

    el = spread["elemental_stats"]
    counts_str = ", ".join(f"{k}: {v}" for k, v in el["counts"].items())
    missing_str = ", ".join(el["missing_elements"]) if el["missing_elements"] else "все стихии представлены"
    lines.extend([
        "--- 4. БАЛАНС СТИХИЙ И РАНГОВ (ПРАВИЛА ЭЛЕМЕНТАЛЬНЫХ ДОСТОИНСТВ ЗОЛОТОЙ ЗАРИ) ---",
        f"• Старших Арканов в раскладе: {el['majors_count']} из {len(spread['cards'])} (показывает степень судьбоносности ситуации)",
        f"• Перевёрнутых карт: {el['reversed_count']} из {len(spread['cards'])}",
        f"• Распределение стихий: {counts_str} | Доминирующая стихия: {el['dominant_element']} | Недостающие стихии: {missing_str}",
    ])

    return "\n".join(lines)
